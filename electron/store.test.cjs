const assert = require("node:assert/strict")
const { test } = require("node:test")
const fs = require("node:fs")
const os = require("node:os")
const path = require("node:path")
const { createStore, normalizeSettings, defaultSettings } = require("./store.cjs")

test("設定は型と範囲を直してから使う", () => {
  const d = defaultSettings("C:\\Users\\u\\Downloads")
  const s = normalizeSettings({ maxConcurrent: 99, cookiesFromBrowser: "evil", rateLimit: "fast", subtitles: "yes", outputDir: " " }, d)
  assert.equal(s.maxConcurrent, 8)
  assert.equal(s.cookiesFromBrowser, "")
  assert.equal(s.rateLimit, "")
  assert.equal(s.subtitles, false)
  assert.equal(s.outputDir, d.outputDir)
  assert.equal(s.adBlock, true)
  assert.deepEqual(normalizeSettings({ extensions: ["C:\\ext", "C:\\ext", 3, ""] }, d).extensions, ["C:\\ext"])
})

test("設定と履歴を保存して読み直す", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "downlee-"))
  const a = createStore(dir, dir)
  a.setSettings({ maxConcurrent: 2 })
  a.addHistory({ id: "1", title: "a" })
  a.addHistory({ id: "1", title: "b" })
  a.flush()
  const b = createStore(dir, dir)
  assert.equal(b.getSettings().maxConcurrent, 2)
  assert.deepEqual(b.listHistory().map((h) => h.title), ["b"])
  b.removeHistory(["1"])
  assert.equal(createStore(dir, dir).listHistory().length, 0)
})
